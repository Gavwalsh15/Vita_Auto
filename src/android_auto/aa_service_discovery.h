#pragma once

#include <cstdint>
#include <vector>

#define AA_VIDEO_RESOLUTION_720P 2
// Current Android Auto VideoFPS enum: NONE=0, _60=1, _30=2.
#define AA_VIDEO_FRAME_RATE_30_FPS 2

namespace android_auto {

inline std::vector<uint8_t> serviceDiscoveryResponse(bool audioOnVita)
{
    // Input, sensors, then 1280x720 H.264 at 30 fps (channels 1-3).
    static constexpr uint8_t inputSensorsVideo[] = {
        0x0a, 0x26, 0x08, 0x01, 0x22, 0x22, 0x08, 0x03, 0x08, 0x04, 0x08, 0x54,
        0x08, 0x17, 0x08, 0x13, 0x08, 0x14, 0x08, 0x15, 0x08, 0x16, 0x08, 0x58,
        0x08, 0x57, 0x08, 0x55, 0x08, 0x80, 0x80, 0x04, 0x12, 0x06, 0x08, 0x80,
        0x0a, 0x10, 0xd0, 0x05, 0x0a, 0x0c, 0x08, 0x02, 0x12, 0x08, 0x0a, 0x02,
        0x08, 0x0a, 0x0a, 0x02, 0x08, 0x0d, 0x0a, 0x15, 0x08, 0x03, 0x1a, 0x11,
        0x08, 0x03, 0x22, 0x0b, 0x08, AA_VIDEO_RESOLUTION_720P, 0x10, AA_VIDEO_FRAME_RATE_30_FPS, 0x18, 0x00, 0x20, 0x00,
        0x28, 0xdc, 0x01, 0x28, 0x01,
    };
    // Optional media and guidance sinks (channels 4-5).
    static constexpr uint8_t musicAndGuidance[] = {
        0x0a, 0x14, 0x08, 0x04, 0x1a, 0x10, 0x08, 0x01, 0x10, 0x03, 0x1a, 0x08,
        0x08, 0x80, 0xf7, 0x02, 0x10, 0x10, 0x18, 0x02, 0x28, 0x01, 0x0a, 0x13,
        0x08, 0x05, 0x1a, 0x0f, 0x08, 0x01, 0x10, 0x01, 0x1a, 0x07, 0x08, 0x80,
        0x7d, 0x10, 0x10, 0x18, 0x01, 0x28, 0x01,
    };
    // Keep system audio (channel 6), as OpenAuto does when disabling music/speech.
    // Microphone (channel 7) and head-unit identification also remain in both modes.
    static constexpr uint8_t systemMicrophoneAndIdentity[] = {
        0x0a, 0x13, 0x08, 0x06, 0x1a, 0x0f, 0x08, 0x01, 0x10, 0x02, 0x1a, 0x07,
        0x08, 0x80, 0x7d, 0x10, 0x10, 0x18, 0x01, 0x28, 0x01,
        0x0a, 0x0f, 0x08, 0x07, 0x2a, 0x0b, 0x08, 0x01, 0x12, 0x07, 0x08, 0x80,
        0x7d, 0x10, 0x10, 0x18, 0x01, 0x12, 0x09, 0x56, 0x69, 0x74, 0x61, 0x20,
        0x41, 0x75, 0x74, 0x6f, 0x1a, 0x10, 0x50, 0x6c, 0x61, 0x79, 0x53, 0x74,
        0x61, 0x74, 0x69, 0x6f, 0x6e, 0x20, 0x56, 0x69, 0x74, 0x61, 0x22, 0x04,
        0x32, 0x30, 0x31, 0x32, 0x2a, 0x0a, 0x56, 0x49, 0x54, 0x41, 0x55, 0x54,
        0x4f, 0x30, 0x31, 0x33, 0x30, 0x00, 0x3a, 0x09, 0x56, 0x69, 0x74, 0x61,
        0x20, 0x41, 0x75, 0x74, 0x6f, 0x42, 0x0c, 0x50, 0x53, 0x20, 0x56, 0x69,
        0x74, 0x61, 0x20, 0x53, 0x6c, 0x69, 0x6d, 0x4a, 0x09, 0x70, 0x63, 0x2d,
        0x62, 0x72, 0x69, 0x64, 0x67, 0x65, 0x52, 0x03, 0x30, 0x2e, 0x31, 0x58,
        0x00, 0x60, 0x00,
    };

    std::vector<uint8_t> out(inputSensorsVideo,
                             inputSensorsVideo + sizeof(inputSensorsVideo));
    if (audioOnVita)
        out.insert(out.end(), musicAndGuidance, musicAndGuidance + sizeof(musicAndGuidance));
    out.insert(out.end(), systemMicrophoneAndIdentity,
               systemMicrophoneAndIdentity + sizeof(systemMicrophoneAndIdentity));
    return out;
}

} // namespace android_auto
